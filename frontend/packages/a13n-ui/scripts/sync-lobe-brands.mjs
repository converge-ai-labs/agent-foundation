import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const catalogVersion = "5.18.0";
const staticSvgVersion = "1.95.0";
const catalogUrl = `https://cdn.jsdelivr.net/npm/@lobehub/icons@${catalogVersion}/es/toc.json`;
const outputPath = fileURLToPath(
  new URL("../src/brand/lobe-brands.generated.ts", import.meta.url),
);

const response = await fetch(catalogUrl);
if (!response.ok) {
  throw new Error(`Failed to fetch ${catalogUrl}: ${response.status}`);
}

const catalog = await response.json();
if (!Array.isArray(catalog)) {
  throw new TypeError(`Expected an array from ${catalogUrl}`);
}

const records = catalog.map((item) => {
  if (!item?.id || !item?.param) {
    throw new TypeError(`Invalid catalog entry: ${JSON.stringify(item)}`);
  }
  const key = item.id.toLowerCase();
  const suffix = item.param.hasColor ? "-color" : "";
  return {
    aliases: aliasVariants(
      item.id,
      item.title,
      item.fullTitle,
      item.docsUrl,
    ).filter((alias) => alias !== key),
    invertInDark: !item.param.hasColor,
    key,
    path: `${key}${suffix}.svg`,
  };
});
const keys = new Set(records.map(({ key }) => key));
const aliasOwners = new Map();
for (const { aliases, key } of records) {
  for (const alias of aliases) {
    const owners = aliasOwners.get(alias) ?? new Set();
    owners.add(key);
    aliasOwners.set(alias, owners);
  }
}

const entries = records
  .map(({ aliases, invertInDark, key, path }) => {
    const unambiguousAliases = aliases.filter(
      (alias) => !keys.has(alias) && aliasOwners.get(alias)?.size === 1,
    );
    const fields = [`icon: \`${"${lobeIconsCdn}"}${path}\``];
    if (unambiguousAliases.length)
      fields.push(`aliases: ${JSON.stringify(unambiguousAliases)}`);
    if (invertInDark) fields.push("invertInDark: true");
    return `  ${JSON.stringify(key)}: { ${fields.join(", ")} },`;
  })
  .sort();

const output = `/**
 * Generated by scripts/sync-lobe-brands.mjs. Do not edit manually.
 * Catalog: @lobehub/icons@${catalogVersion}
 * Assets: @lobehub/icons-static-svg@${staticSvgVersion}
 */
import type { Brand } from "./brands";

export const lobeIconsCdn =
  "https://cdn.jsdelivr.net/npm/@lobehub/icons-static-svg@${staticSvgVersion}/icons/";

export const lobeBrands = {
${entries.join("\n")}
} satisfies Record<string, Brand>;
`;

await writeFile(outputPath, await format(output, { parser: "typescript" }));
process.stdout.write(
  `Wrote ${entries.length} LobeHub brands to ${outputPath}\n`,
);

function aliasVariants(...values) {
  const aliases = new Set();
  for (const value of values) {
    if (typeof value !== "string") continue;
    const normalized = value.trim().toLowerCase();
    if (!normalized) continue;
    aliases.add(normalized);
    aliases.add(separated(normalized, "-"));
    aliases.add(separated(normalized, "_"));
    aliases.add(normalized.replace(/[^\p{L}\p{N}]+/gu, ""));
  }
  aliases.delete("");
  return [...aliases];
}

function separated(value, separator) {
  return value
    .replace(/[^\p{L}\p{N}]+/gu, separator)
    .replace(new RegExp(`^\\${separator}+|\\${separator}+$`, "g"), "");
}
