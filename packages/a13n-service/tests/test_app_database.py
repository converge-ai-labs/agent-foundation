@pytest.fixture
def app_database(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    monkeypatch.syspath_prepend(str(tmp_path))

    def declare(app_id="acme.reports", *, prefix=None, migrations=None):
        if migrations is None:
            package = f"app_test_{uuid4().hex}"
            root = tmp_path / package
            root.mkdir()
            (root / "__init__.py").write_text("")
            importlib.invalidate_caches()
            migrations = f"{package}:migrations"
        return AppDatabase(app_id, migrations=migrations, prefix=prefix)

    return declare


def notes(database: AppDatabase) -> Table:
    return Table(
        database.name("notes"),
        database.metadata,
        Column("id", Integer, primary_key=True),
        Column("body", String, nullable=False, index=True, server_default=text("'app__acme_reports__notes'")),
    )


def sql(database: Database, statement: str):
    engine = create_engine(database.url.get_secret_value())
    try:
        with engine.begin() as connection:
            return (
                connection.execute(text(statement)).fetchall()
                if statement.lstrip().startswith("SELECT")
                else connection.execute(text(statement))
            )
    finally:
        engine.dispose()


def test_namespace_declarations_and_collisions(app_database):
    database = app_database()
    assert database.name("notes") == "app__acme_reports__notes"
    assert database.version_table == "app__acme_reports__alembic_version"
    assert app_database(prefix="reports_1").name("notes") == "app__reports_1__notes"
    for prefix in ("Reports", "a-b", "a__b", "a" * 25, "x;DROP"):
        with pytest.raises(ValueError, match="prefix"):
            app_database(prefix=prefix)
    with pytest.raises(ValueError, match="reserved"):
        database.name("alembic_version")
    with pytest.raises(ValueError, match="63 bytes"):
        database.name("n" * 63)
    Table("native", database.metadata, Column("id", Integer, primary_key=True))
    with pytest.raises(ValueError, match="namespace"):
        database.validate()

    first = app_database("acme.reports")
    second = app_database("acme_reports")
    installed = tuple(
        InstalledApp(AppDefinition(db.app_id, "Demo", database=db), "demo", "1") for db in (first, second)
    )
    with pytest.raises(ValueError, match="Duplicate App database prefix"):
        app_databases(installed)
    with pytest.raises(ValueError, match="identity"):
        AppDefinition("other", "Demo", database=first)


def test_independent_histories_generation_and_retained_ownership(database, app_database):
    first, second = app_database(), app_database("acme.tasks")
    first_table, second_table = notes(first), notes(second)
    apps.initialize(first)
    apps.initialize(second)
    before = sql(database, "SELECT tablename FROM pg_tables WHERE schemaname='public' ORDER BY 1")
    path = apps.generate(database, OSS, first, "create reports")
    apps.generate(database, OSS, second, "create tasks")
    assert sql(database, "SELECT tablename FROM pg_tables WHERE schemaname='public' ORDER BY 1") == before
    source = path.read_text()
    assert "migration_name('notes')" in source
    assert "'app__acme_reports__notes'" in source  # A default literal is data, not an identifier.
    assert "migration_name('notes__ix_body')" in source
    apps.upgrade(database, OSS, second)
    apps.upgrade(database, OSS, first)
    assert apps.status(database, OSS, first)["ready"]
    sql(database, f"INSERT INTO {first_table.name} (id, body) VALUES (1, 'saved')")
    # Installed and uninstalled namespaces are both invisible to Core drift detection.
    sql(database, "CREATE TABLE app__retained__data (id integer)")
    runner.check(database, OSS)
    with apps.migration_connection(database, OSS, first) as config:
        command.check(config)
    sql(database, "CREATE TABLE unknown_native (id integer)")
    with pytest.raises(AutogenerateDiffsDetected, match="remove_table"):
        runner.check(database, OSS)
    sql(database, "DROP TABLE unknown_native")
    first_table.append_column(Column("rating", Integer, nullable=False, server_default=text("0")))
    apps.generate(database, OSS, first, "add rating")
    assert not apps.status(database, OSS, first)["ready"]
    apps.upgrade(database, OSS, first)
    assert sql(database, f"SELECT body, rating FROM {first_table.name}") == [("saved", 0)]
    assert apps.status(database, OSS, second)["ready"]
    apps.check(database, OSS, first)
    # Removing a model produces a drop draft across the whole owned prefix, not just current model names.
    first.metadata.remove(first_table)
    drop = apps.generate(database, OSS, first, "remove notes").read_text()
    assert "op.drop_table(migration_name('notes'))" in drop
    assert second_table.name not in drop and "unknown_native" not in drop
    assert sql(database, f"SELECT body FROM {first_table.name}") == [("saved",)]
    changed = app_database(prefix="other", migrations=first.migrations)
    with pytest.raises(ValueError, match="retained ownership"):
        apps.upgrade(database, OSS, changed)
    conflict = app_database("different", prefix="acme_reports", migrations=first.migrations)
    with pytest.raises(ValueError, match="retained ownership"):
        apps.upgrade(database, OSS, conflict)


def test_deployment_override_reuses_published_history(database, app_database):
    from sqlalchemy import CheckConstraint, UniqueConstraint
    from sqlalchemy.dialects.postgresql import ENUM

    def models(definition):
        table = notes(definition)
        table.append_column(Column("parent_id", Integer, ForeignKey(f"{table.name}.id")))
        table.append_column(Column("state", ENUM("draft", "ready", name=definition.name("state"))))
        long_column = "long_column_" + "x" * 38
        table.append_column(Column(long_column, String))
        table.append_constraint(UniqueConstraint(long_column))
        table.append_constraint(CheckConstraint("id > 0", name=definition.name("positive")))
        return table

    source = app_database()
    models(source)
    apps.initialize(source)
    apps.generate(database, OSS, source, "create notes")
    selected = app_database(prefix="deployment_2", migrations=source.migrations)
    models(selected)
    with scratch_database(database) as target:
        runner.upgrade(target, OSS)
        assert apps.status(target, OSS, selected)["bound"] is False
        apps.upgrade(target, OSS, selected)
        with apps.migration_connection(target, OSS, selected) as config:
            command.check(config)
        assert sql(target, f"SELECT count(*) FROM {selected.name('notes')}") == [(0,)]
        assert sql(target, "SELECT to_regclass('app__acme_reports__notes')") == [(None,)]
        apps.check(target, OSS, selected)
    sql(database, f"CREATE TABLE {source.name('orphan')} (id integer)")
    with pytest.raises(ValueError, match="occupied"):
        apps.upgrade(database, OSS, source)
    assert sql(database, "SELECT count(*) FROM app_databases") == [(0,)]


@pytest.mark.anyio
async def test_native_orm_join_uses_host_storage(database, app_database, runtime, tenant):
    database_definition = app_database()
    database_definition.reference(WorkspaceRow.__table__)

    class AppBase(DeclarativeBase):
        metadata = database_definition.metadata

    class Note(AppBase):
        __tablename__ = database_definition.name("notes")
        id: Mapped[int] = mapped_column(primary_key=True)
        workspace_id: Mapped[str] = mapped_column(ForeignKey("workspaces.id"), index=True)
        body: Mapped[str]

    apps.initialize(database_definition)
    apps.generate(database, OSS, database_definition, "create scoped notes")
    apps.upgrade(database, OSS, database_definition)
    async with transaction(runtime.storage) as session:
        session.add(Note(id=1, workspace_id=tenant.workspace_id, body="native join"))
    async with transaction(runtime.storage) as session:
        result = (
            await session.execute(
                select(Note.body, WorkspaceRow.id).join(WorkspaceRow, Note.workspace_id == WorkspaceRow.id)
            )
        ).one()
    assert result == ("native join", tenant.workspace_id)
    await apps.require_current(runtime.storage, (database_definition,))
    with apps.migration_connection(database, OSS, database_definition) as config:
        command.check(config)


@pytest.mark.anyio
@pytest.mark.parametrize("role", ["all", "control", "worker"])
async def test_startup_refuses_app_schema_before_any_callback(settings: Settings, app_database, role):
    definition = app_database()
    notes(definition)
    apps.initialize(definition)
    apps.generate(settings.database, OSS, definition, "initial")
    events = []

    async def start(runtime, stack):
        events.append("started")

    installed = (
        InstalledApp(AppDefinition(definition.app_id, "Demo", database=definition, startup=start), "demo", "1"),
    )
    app = assembly.build_app(settings=settings, apps=installed, role=role)
    with pytest.raises(RuntimeError, match="apps db upgrade"):
        async with app.router.lifespan_context(app):
            pytest.fail("Unprepared App must not start")
    assert not events
    apps.upgrade(settings.database, OSS, definition)
    async with AsyncExitStack() as stack:
        await assembly.open_runtime(stack, OSS, settings, executes=False, apps=installed)
    assert events == ["started"]
    sql(settings.database, f"UPDATE {definition.version_table} SET version_num='unknown'")
    with pytest.raises(RuntimeError, match="apps db upgrade"):
        async with AsyncExitStack() as stack:
            await assembly.open_runtime(stack, OSS, settings, executes=False, apps=installed)
    assert events == ["started"]


def test_cli_app_database_workflow(database, app_database, tmp_path, monkeypatch, clean_environment):
    definition = app_database()
    notes(definition)
    installed = (InstalledApp(AppDefinition(definition.app_id, "Demo", database=definition), "demo", "1"),)
    calls = []

    def discover():
        calls.append("discover")
        return installed

    monkeypatch.setattr(cli, "discover_apps", discover)
    config = tmp_path / "service.toml"
    config.write_text(f'[database]\nurl = "{database.url.get_secret_value()}"\n')
    runner_cli = CliRunner()

    def invoke(*arguments):
        result = runner_cli.invoke(cli.main, ["--config", str(config), *arguments])
        assert result.exit_code == 0, result.output + str(result.exception)
        return result

    invoke("apps", "db", "init")
    invoke("apps", "db", "revision", "-m", "initial")
    assert json.loads(invoke("apps", "db", "status").output.splitlines()[-1])["ready"] is False
    invoke("apps", "db", "check")
    invoke("migrate", "--apps")
    assert json.loads(invoke("apps", "db", "status").output.splitlines()[-1])["ready"] is True
    invoke("apps", "db", "upgrade", "--app", definition.app_id)
    assert len(calls) == 7
    with create_engine(database.url.get_secret_value()).connect() as connection:
        assert definition.name("notes") in inspect(connection).get_table_names()


def test_packaged_history_resources_are_readable_but_not_generation_targets(
    database, app_database, tmp_path, monkeypatch
):
    from zipfile import ZipFile

    source = app_database()
    notes(source)
    root = apps.initialize(source)
    apps.generate(database, OSS, source, "create packaged notes")
    package = f"packaged_{uuid4().hex}"
    archive = tmp_path / "app.zip"
    with ZipFile(archive, "w") as wheel:
        wheel.writestr(f"{package}/__init__.py", "")
        for path in root.rglob("*.py"):
            wheel.write(path, f"{package}/migrations/{path.relative_to(root).as_posix()}")
    monkeypatch.syspath_prepend(str(archive))
    importlib.invalidate_caches()
    packaged = app_database(prefix="packaged", migrations=f"{package}:migrations")
    notes(packaged)
    assert apps.heads(packaged) == apps.heads(source)
    apps.check(database, OSS, packaged)
    with pytest.raises(ValueError, match="source package"):
        apps.generate(database, OSS, packaged, "must not write extracted files")
    with pytest.raises(ValueError, match="source package"):
        apps.initialize(packaged)


def test_app_upgrades_serialize_and_retain_binding_after_failure(database, app_database):
    from concurrent.futures import ThreadPoolExecutor

    definition = app_database()
    notes(definition)
    apps.initialize(definition)
    path = apps.generate(database, OSS, definition, "create notes")
    source = path.read_text()
    path.write_text(
        source.replace("def upgrade() -> None:", "def upgrade() -> None:\n    raise RuntimeError('planned failure')")
    )
    with pytest.raises(RuntimeError, match="planned failure"):
        apps.upgrade(database, OSS, definition)
    assert sql(database, "SELECT app_id, prefix FROM app_databases") == [(definition.app_id, definition.prefix)]
    assert sql(database, f"SELECT to_regclass('{definition.name('notes')}')") == [(None,)]
    path.write_text(source)
    # The failed connection released its session lock. Concurrent retries converge without double DDL.
    with ThreadPoolExecutor(max_workers=2) as workers:
        results = [workers.submit(apps.upgrade, database, OSS, definition) for _ in range(2)]
        for result in results:
            result.result(timeout=30)
    assert apps.status(database, OSS, definition)["ready"]
